import fs from 'node:fs'
import path from 'node:path'
import { normalizePath, type Plugin } from 'vite'
import { parseSvg } from './parse-svg.js'
import { isIconFile } from './paths.js'

const VIRTUAL_MODULE_ID = 'virtual:usesvelte/inline-svg'
const RESOLVED_VIRTUAL_MODULE_ID = `\0${VIRTUAL_MODULE_ID}`

/** First line of the declaration file the plugin writes, used to tell ours from foreign ones. */
const TYPES_HEADER = '// Generated by @usesvelte/inline-svg. Do not edit.'
/** Name of the declaration file the plugin writes next to the svgs. */
const TYPES_FILE = 'inline-svg.d.ts'

export interface InlineSvgPluginOptions {
  /**
   * Directory that contains the svgs, relative to the project root.
   *
   * @default 'src/icons'
   */
  dir?: string

  /**
   * Path, relative to the project root, of the declaration file that types the icons virtual
   * module with the names of the icons directory, so that consumers can
   * `import type { IconName } from 'virtual:usesvelte/inline-svg'`. `false` disables the generation.
   *
   * @default '<dir>/inline-svg.d.ts'
   */
  types?: string | false
}

function findSvgs(dir: string): string[] {
  return fs
    .readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      if (!entry.name.toLowerCase().endsWith('.svg')) return false
      try {
        return fs.statSync(path.join(entry.parentPath, entry.name)).isFile()
      } catch {
        return false
      }
    })
    .map((entry) => path.join(entry.parentPath, entry.name))
    .sort()
}

function toIconName(file: string, dir: string): string {
  return path
    .relative(dir, file)
    .split(path.sep)
    .join('/')
    .replace(/\.svg$/i, '')
}

/**
 * Content of the declaration that types the icons virtual module with the given icon names, so
 * that consumers can `import type { IconName } from 'virtual:usesvelte/inline-svg'`. Virtual
 * module ids can only be declared from a script file (without imports or exports). The union is
 * written vertically, one member per line, so that it does not grow wide with many icons.
 */
function renderTypesDeclaration(names: Iterable<string>): string {
  const members = [...names].sort().map((name) => `    | ${JSON.stringify(name)}`)
  return [
    TYPES_HEADER,
    `declare module 'virtual:usesvelte/inline-svg' {`,
    '  /** Names of the svgs of the icons directory, typed by the inlineSvg vite plugin */',
    ...(members.length === 0 ? ['  export type IconName = never'] : ['  export type IconName =', ...members]),
    '}',
    '',
  ].join('\n')
}

function readIfExists(file: string): string | null {
  try {
    return fs.readFileSync(file, 'utf8')
  } catch {
    return null
  }
}

/**
 * Re-reads the virtual module when one of the svgs is added, changed or removed, so that the
 * icons of the directory are always the ones the dev server hands over to the browser.
 */
function refreshIconsModule<T>(
  file: string,
  iconsDirPosix: string,
  getModule: (id: string) => T | undefined,
  invalidateModule: (mod: T) => void,
): T[] | undefined {
  if (!isIconFile(file, iconsDirPosix)) return

  const icons = getModule(RESOLVED_VIRTUAL_MODULE_ID)
  if (!icons) return

  invalidateModule(icons)

  return [icons]
}

/**
 * Makes the svgs of the icons directory available to `InlineSvg` as a virtual module, so that the
 * library never has to reach into the consumer's filesystem from `node_modules`. It also writes a
 * declaration file next to the svgs that types the `name` prop with the real icon names.
 */
export function inlineSvg(options: InlineSvgPluginOptions = {}): Plugin {
  const dir = options.dir ?? 'src/icons'

  let iconsDir = path.resolve(dir)
  let iconsDirPosix = normalizePath(iconsDir)
  let typesFile =
    options.types === false ? null : normalizePath(path.resolve(options.types ?? path.join(dir, TYPES_FILE)))

  /**
   * Writes the declaration that types the icons virtual module with the given icon names, or
   * removes our stale declaration when they are `null` (the icons could not be read), so that
   * the names never outlive the svgs. A file that was not generated by the plugin is never
   * overwritten. Only writes when the content changed, since `load()` runs once per environment
   * (client and ssr) and on every icons refresh.
   */
  function writeIconNames(names: Iterable<string> | null, warn: (message: string) => void) {
    if (typesFile == null) return

    if (names == null) {
      if (readIfExists(typesFile)?.startsWith(TYPES_HEADER) !== true) return
      try {
        fs.rmSync(typesFile)
      } catch (error) {
        warn(`icon names types cannot be removed: ${typesFile}. ${error}`)
      }
      return
    }

    const declaration = renderTypesDeclaration([...names])
    const existing = readIfExists(typesFile)
    if (existing === declaration) return
    if (existing != null && !existing.startsWith(TYPES_HEADER)) {
      warn(`icon names types not written: ${typesFile} exists and was not generated by @usesvelte/inline-svg`)
      return
    }

    try {
      fs.mkdirSync(path.dirname(typesFile), { recursive: true })
      fs.writeFileSync(typesFile, declaration)
    } catch (error) {
      warn(`icon names types cannot be written: ${typesFile}. ${error}`)
    }
  }

  return {
    name: 'usesvelte:inline-svg',

    config() {
      return {
        // The library is served as source, otherwise the icons virtual module would be
        // inlined into the pre-bundled dependency and new svgs would need a restart.
        optimizeDeps: {
          exclude: ['@usesvelte/inline-svg'],
        },
      }
    },

    configResolved(config) {
      iconsDir = path.resolve(config.root, dir)
      iconsDirPosix = normalizePath(iconsDir)
      typesFile =
        options.types === false
          ? null
          : normalizePath(path.resolve(config.root, options.types ?? path.join(dir, TYPES_FILE)))
    },

    resolveId(id) {
      return id === VIRTUAL_MODULE_ID ? RESOLVED_VIRTUAL_MODULE_ID : null
    },

    load(id) {
      if (id !== RESOLVED_VIRTUAL_MODULE_ID) return null

      const stat = fs.statSync(iconsDir, { throwIfNoEntry: false })
      if (stat == null) {
        this.warn(`icons directory not found: ${iconsDir}. Is the "dir" option of inlineSvg() correct?`)
        writeIconNames(null, (message) => this.warn(message))
        return 'export const icons = {}'
      }
      if (!stat.isDirectory()) {
        this.warn(`icons path is not a directory: ${iconsDir}. "dir" must point to a directory`)
        writeIconNames(null, (message) => this.warn(message))
        return 'export const icons = {}'
      }

      let files: string[]
      try {
        files = findSvgs(iconsDir)
      } catch (error) {
        this.warn(`icons directory cannot be read: ${iconsDir}. ${error}`)
        writeIconNames(null, (message) => this.warn(message))
        return 'export const icons = {}'
      }

      if (files.length === 0) this.warn(`no svg found in: ${iconsDir}`)

      for (const file of files) this.addWatchFile(file)

      const names = new Map<string, string[]>()
      for (const file of files) {
        const name = toIconName(file, iconsDir)
        const group = names.get(name)
        if (group) group.push(file)
        else names.set(name, [file])
      }
      for (const [name, group] of names) {
        if (group.length > 1) {
          const sources = group.map((file) => path.relative(iconsDir, file)).join(', ')
          this.warn(`duplicate icon name: "${name}" (${sources})`)
        }
      }

      writeIconNames(names.keys(), (message) => this.warn(message))

      const entries = files.map((file) => {
        const name = toIconName(file, iconsDir)
        const raw = fs.readFileSync(file, 'utf8')
        const { attrs, content } = parseSvg(raw, name)
        return `  ${JSON.stringify(name)}: ${JSON.stringify({ attrs, content })},`
      })

      return ['export const icons = {', ...entries, '}', ''].join('\n')
    },

    watchChange(id, change) {
      if (change.event !== 'create' && change.event !== 'delete') return
      const { environment } = this
      if (!('moduleGraph' in environment)) return
      refreshIconsModule(
        id,
        iconsDirPosix,
        (moduleId) => environment.moduleGraph.getModuleById(moduleId),
        (mod) => environment.moduleGraph.invalidateModule(mod),
      )
    },

    hotUpdate({ file }) {
      return refreshIconsModule(
        file,
        iconsDirPosix,
        (id) => this.environment.moduleGraph.getModuleById(id),
        (mod) => this.environment.moduleGraph.invalidateModule(mod),
      )
    },

    // Vite 5 does not know about the `hotUpdate` hook yet.
    handleHotUpdate({ file, server }) {
      return refreshIconsModule(
        file,
        iconsDirPosix,
        (id) => server.moduleGraph.getModuleById(id),
        (mod) => server.moduleGraph.invalidateModule(mod),
      )
    },
  }
}
